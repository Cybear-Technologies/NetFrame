// Sources of truth (nothing here is hand-copied):
//   - class names: compiled from packages/netframe/src/{components,utilities}/_*.scss
//   - class descriptions: "Class reference" tables in the docs MDX pages
//   - tokens and themes: packages/netframe/dist/netframe.css and themes.css
//   - interactive patterns: ComponentDemo markup and `## JavaScript` snippets in the docs
//
// Usage:
//   node scripts/build-skills.mjs          write generated files
//   node scripts/build-skills.mjs --check  exit 1 if any generated file is stale
//
// Requires a built library (dist/); `pnpm --filter netframe run build` first.
// No version stamps are written: the Changesets version PR must not need a regeneration.

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PKG = path.join(ROOT, 'packages', 'netframe');
const DOCS_PAGES = path.join(ROOT, 'apps', 'docs', 'src', 'pages');
const SKILLS = path.join(PKG, 'skills');
const SITE = 'https://netframe.cybeartech.com';
const CHECK = process.argv.includes('--check');

const require = createRequire(path.join(PKG, 'package.json'));
const sass = require('sass');
const postcss = require('postcss');

const read = (file) => fs.readFileSync(file, 'utf8');
const stems = (dir) =>
  fs.readdirSync(dir)
    .filter((f) => f.startsWith('_') && f.endsWith('.scss') && f !== '_index.scss')
    .map((f) => f.slice(1, -5))
    .sort();

// ---------------------------------------------------------------------------
// Docs parsing
// ---------------------------------------------------------------------------

function docsPage(kind, name) {
  return read(path.join(DOCS_PAGES, kind, `${name}.mdx`));
}

function classDescriptions() {
  const map = new Map();
  for (const kind of ['components', 'utilities']) {
    for (const file of fs.readdirSync(path.join(DOCS_PAGES, kind)).sort()) {
      const mdx = read(path.join(DOCS_PAGES, kind, file));
      const section = mdx.split(/^## Class reference$/m)[1] ?? '';
      for (const row of section.matchAll(/^\|\s*`(nf-[a-z0-9-]+)`\s*\|\s*(.+?)\s*\|\s*$/gm)) {
        if (!map.has(row[1])) map.set(row[1], row[2]);
      }
    }
  }
  return map;
}

function jsSnippet(mdx, heading) {
  const re = new RegExp(`^## ${heading}\\s[\\s\\S]*?\`\`\`js\\n([\\s\\S]*?)\`\`\``, 'm');
  return re.exec(mdx)?.[1]?.trimEnd() ?? null;
}

// MDX strips two spaces of indentation from every line after the first inside a
// ComponentDemo `code` attribute, so the docs source indents those lines two spaces
// deeper than the snippet readers see. Undo that offset to match what is rendered.
function firstDemoMarkup(mdx) {
  const m = /<ComponentDemo[^>]*code=\{`([\s\S]*?)`\}>/.exec(mdx);
  if (!m) return null;
  const [first, ...rest] = m[1].split('\n');
  return [first, ...rest.map((l) => (l.startsWith('  ') ? l.slice(2) : l))].join('\n').trimEnd();
}

// ---------------------------------------------------------------------------
// Compiled CSS parsing
// ---------------------------------------------------------------------------

function classesOf(scssFile) {
  const css = sass.compile(scssFile, { style: 'expanded' }).css;
  const found = new Set();
  postcss.parse(css).walkRules((rule) => {
    for (const m of rule.selector.matchAll(/\.(nf-[a-z0-9-]+)/g)) found.add(m[1]);
  });
  return [...found].sort();
}

function rootTokens() {
  const tokens = [];
  postcss.parse(read(path.join(PKG, 'dist', 'netframe.css'))).walkRules(':root', (rule) => {
    rule.walkDecls(/^--nf-/, (d) => tokens.push([d.prop, d.value]));
  });
  return tokens;
}

function themes() {
  const out = [];
  postcss.parse(read(path.join(PKG, 'dist', 'themes.css'))).walkRules((rule) => {
    const m = /^\.(nf-theme-[a-z0-9-]+)$/.exec(rule.selector.trim());
    if (!m) return;
    const decls = [];
    rule.walkDecls(/^--nf-/, (d) => decls.push([d.prop, d.value]));
    out.push([m[1], decls]);
  });
  return out;
}

// ---------------------------------------------------------------------------
// Generated documents
// ---------------------------------------------------------------------------

const HEADER = (what) =>
  `<!-- GENERATED by scripts/build-skills.mjs from ${what}. Do not edit; run \`pnpm skills:build\`. -->\n\n`;
const esc = (s) => s.replace(/\|/g, '\\|');
const title = (s) => s.charAt(0).toUpperCase() + s.slice(1);

function buildClasses() {
  const descriptions = classDescriptions();
  let md = HEADER('the compiled SCSS and the docs class-reference tables');
  md += '# NetFrame class reference\n\n';
  md += 'Every class below exists in the shipped CSS. A dash means the docs page does not describe it; read the page.\n\n';
  // Utility classes (e.g. nf-hidden) are listed once, under their utility group,
  // even when a component stylesheet also references them as a modifier.
  const utilityClasses = new Set(
    stems(path.join(PKG, 'src', 'utilities')).flatMap((n) => classesOf(path.join(PKG, 'src', 'utilities', `_${n}.scss`))),
  );
  for (const [kind, label] of [['components', 'Component'], ['utilities', 'Utility group']]) {
    for (const name of stems(path.join(PKG, 'src', kind))) {
      const classes = classesOf(path.join(PKG, 'src', kind, `_${name}.scss`))
        .filter((c) => kind === 'utilities' || !utilityClasses.has(c));
      if (!classes.length) continue;
      md += `## ${title(name)} (${label.toLowerCase()})\n\nDocs: ${SITE}/${kind}/${name}/\n\n| Class | Description |\n| --- | --- |\n`;
      for (const cls of classes) md += `| \`${cls}\` | ${esc(descriptions.get(cls) ?? '—')} |\n`;
      md += '\n';
    }
  }
  return md.trimEnd() + '\n';
}

function buildTokens() {
  const tokens = rootTokens();
  const groups = new Map();
  for (const [name, value] of tokens) {
    const group = name.replace(/^--nf-/, '').split('-')[0];
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push([name, value]);
  }
  let md = HEADER('dist/netframe.css and dist/themes.css');
  md += '# NetFrame tokens\n\nDefault values on `:root`. Override any token with plain CSS; no rebuild.\n\n';
  for (const [group, list] of groups) {
    md += `## ${group}\n\n| Token | Default |\n| --- | --- |\n`;
    for (const [name, value] of list) md += `| \`${name}\` | \`${esc(value)}\` |\n`;
    md += '\n';
  }
  md += '## Alternate themes\n\nApply one class to `<html>` (or any container). Each overrides the tokens listed; everything else falls back to the defaults above.\n\n';
  for (const [name, decls] of themes()) {
    md += `### \`${name}\`\n\n| Token | Value |\n| --- | --- |\n`;
    for (const [prop, value] of decls) md += `| \`${prop}\` | \`${esc(value)}\` |\n`;
    md += '\n';
  }
  return md.trimEnd() + '\n';
}

// Behaviour is consumer-owned. These patterns are the docs' own controllers.
const PATTERNS = [
  { name: 'accordion', page: 'components/accordion', heading: 'JavaScript' },
  { name: 'dropdown', page: 'components/dropdown', heading: 'JavaScript' },
  { name: 'tabs', page: 'components/tabs', heading: 'JavaScript' },
  { name: 'modal', page: 'components/modal', heading: 'JavaScript' },
  { name: 'drawer', page: 'components/drawer', heading: 'JavaScript' },
  { name: 'toast', page: 'components/toast', heading: 'Usage' },
  { name: 'table sorting', page: 'components/table', heading: 'JavaScript', markup: false },
  {
    name: 'pagination',
    page: 'components/pagination',
    heading: 'JavaScript',
    markup: false,
    note: 'Required container markup (see the docs page for the full example): `<div data-pagination data-pages="N" data-page="1"><nav aria-label="Pagination"><ol class="nf-pagination"></ol></nav><p data-page-status role="status"></p><ul data-page-results></ul></div>`. The controller rebuilds the list items.',
  },
  {
    name: 'notification disclosure (badge dot)',
    page: 'components/badge',
    heading: 'JavaScript',
    markup: false,
    note: 'Needs the container with `data-notifications`, a trigger with `data-notification-trigger`, a hidden `.notification-panel`, and `data-notification-count`, `data-notification-label`, `data-notification-status`, `data-mark-read` hooks. Copy the full HTML and demo-only CSS from the docs page.',
  },
];

function buildPatterns() {
  let md = HEADER('the docs MDX pages (the same snippets the browser tests execute)');
  md += '# NetFrame interactive patterns\n\nNetFrame ships CSS only. These optional controllers are copied from the docs and run in the docs test suite. State lives in ARIA attributes; use unique `id`s per instance.\n\n';
  for (const p of PATTERNS) {
    const mdx = docsPage(...p.page.split('/'));
    const js = jsSnippet(mdx, p.heading);
    if (!js) throw new Error(`no ${p.heading} JavaScript snippet in ${p.page}.mdx`);
    md += `## ${title(p.name)}\n\nDocs: ${SITE}/${p.page}/\n\n`;
    if (p.note) md += `${p.note}\n\n`;
    const markup = p.markup === false ? null : firstDemoMarkup(mdx);
    if (markup) md += `Reference markup:\n\n\`\`\`html\n${markup}\n\`\`\`\n\n`;
    md += `Controller:\n\n\`\`\`js\n${js}\n\`\`\`\n\n`;
  }
  return md.trimEnd() + '\n';
}

function skillBodies() {
  return fs.readdirSync(SKILLS).sort().filter((d) => fs.existsSync(path.join(SKILLS, d, 'SKILL.md'))).map((d) => {
    const raw = read(path.join(SKILLS, d, 'SKILL.md'));
    return [d, raw.replace(/^---\n[\s\S]*?\n---\n/, '').trim()];
  });
}

function buildLlmsFull(generated) {
  let md = '# NetFrame (full reference for LLM agents)\n\n';
  md += `> Cyberpunk CSS component library by Cybear Technologies. Plain CSS, no JavaScript runtime. Docs: ${SITE}\n\n`;
  md += 'Generated from the repository by `scripts/build-skills.mjs`.\n\n';
  for (const [name, body] of skillBodies()) md += `---\n\n<!-- skill: ${name} -->\n\n${body}\n\n`;
  md += `---\n\n${generated.classes.replace(/^<!--.*-->\n\n/, '')}\n---\n\n${generated.tokens.replace(/^<!--.*-->\n\n/, '')}\n---\n\n${generated.patterns.replace(/^<!--.*-->\n\n/, '')}`;
  return md;
}

function buildLlms() {
  const pages = [];
  for (const kind of ['components', 'utilities']) {
    for (const file of fs.readdirSync(path.join(DOCS_PAGES, kind)).sort()) {
      const mdx = read(path.join(DOCS_PAGES, kind, file));
      const t = /^title:\s*'(.+)'$/m.exec(mdx)?.[1] ?? file;
      const d = /^description:\s*'(.+)'$/m.exec(mdx)?.[1] ?? '';
      pages.push(`- [${t}](${SITE}/${kind}/${file.replace('.mdx', '')}/): ${d}`);
    }
  }
  return `# NetFrame

> Cyberpunk CSS component library by Cybear Technologies. Plain CSS with \`nf-\` classes and \`--nf-*\` tokens, seven palettes, self-hosted fonts, no JavaScript runtime. npm package: \`netframe\`.

Install: \`npm install netframe\`, then \`import 'netframe/dist/netframe.css'\` (optional: \`netframe/dist/themes.css\`).

## Reference for agents

- [Full reference (usage, theming, interactive patterns, every class and token)](${SITE}/llms-full.txt)
- [Agent skills (Claude Code, GitHub Copilot, Codex)](${SITE}/agents/)

## Guides

- [Getting started](${SITE}/getting-started/): install, imports, Sass, fonts
- [Theming](${SITE}/theming/): tokens and alternate themes

## Components

${pages.filter((p) => p.includes('/components/')).join('\n')}

## Utilities

${pages.filter((p) => p.includes('/utilities/')).join('\n')}
`;
}

// ---------------------------------------------------------------------------
// Write or check
// ---------------------------------------------------------------------------

const generated = { classes: buildClasses(), tokens: buildTokens(), patterns: buildPatterns() };
const outputs = new Map([
  [path.join(SKILLS, 'netframe-usage', 'references', 'classes.md'), generated.classes],
  [path.join(SKILLS, 'netframe-theming', 'references', 'tokens.md'), generated.tokens],
  [path.join(SKILLS, 'netframe-interactive', 'references', 'patterns.md'), generated.patterns],
  [path.join(ROOT, 'apps', 'docs', 'public', 'llms-full.txt'), buildLlmsFull(generated)],
  [path.join(ROOT, 'apps', 'docs', 'public', 'llms.txt'), buildLlms()],
]);

const stale = [];
for (const [file, content] of outputs) {
  const current = fs.existsSync(file) ? read(file) : null;
  if (current === content) continue;
  stale.push(path.relative(ROOT, file));
  if (!CHECK) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, 'utf8');
  }
}

if (CHECK && stale.length) {
  console.error(`Generated agent files are stale (run \`pnpm skills:build\`):\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
console.log(CHECK ? 'Agent skill references are up to date.' : `Wrote ${stale.length} changed file(s) of ${outputs.size}.`);
